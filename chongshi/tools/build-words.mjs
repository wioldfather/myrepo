// Generates js/words.gen.js, the graded word bank behind the level check and the Words deck.
//
// Source: "Complete HSK Vocabulary" by Yanis Zafirópulos (MIT), which combines the official HSK word lists
// with CC-CEDICT definitions (CC BY-SA 4.0) and corpus frequency ranks.
//   https://github.com/drkameleon/complete-hsk-vocabulary  →  complete.min.json
// Run: node tools/build-words.mjs path/to/complete.min.json
//
// Levels 1-6 are the classic HSK (2.0) lists, 5,000 words in all. Level 7 is the advanced band of the
// 2021 standard (HSK 7-9), trimmed to its more frequent words.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const src = process.argv[2];
if (!src) throw new Error('usage: node tools/build-words.mjs path/to/complete.min.json');
const data = JSON.parse(readFileSync(src, 'utf8'));

const ADVANCED_MAX_RANK = 22000; // keep the commoner three quarters of the 7-9 band
const SKIP = /^(variant of|old variant|archaic variant|see |see also|used in |surname |abbr\. for|also written|also pr\.|erhua variant|classifier for|\(particle|\(interjection|interjection|\(used |\(onom|\(dialect|\(archaic|\(old\))/i;
const PROPER = new Set(['nr', 'ns', 'nt', 'nz']);

function gloss(meanings) {
  const parts = [];
  for (const m of meanings) {
    if (SKIP.test(m)) continue;
    for (let seg of m.split(';')) {
      seg = seg.replace(/\s*\((idiom|loanword|coll\.|bound form|literary|fig\.|lit\.)\)/gi, '').replace(/\s*CL:.*$/, '').replace(/\s+/g, ' ').trim();
      if (seg.length < 2 || seg.startsWith('(') || parts.includes(seg)) continue;
      parts.push(seg);
    }
  }
  if (!parts.length) return '';
  let out = parts[0];
  if (parts[1] && out.length + parts[1].length <= 44) out += '; ' + parts[1];
  return out.length > 60 ? out.slice(0, 57).replace(/[ ,;]+\S*$/, '') + '…' : out;
}
const posClass = (p) => { const x = (p[0] || 'o')[0].toLowerCase(); return 'vnad'.includes(x) ? x : 'o'; };

const levels = { 1: [], 2: [], 3: [], 4: [], 5: [], 6: [], 7: [] };
let dropped = 0;
for (const e of data) {
  const old = e.l.find((l) => l[0] === 'o');
  const lv = old ? +old[1] : e.l.includes('n7') && e.q <= ADVANCED_MAX_RANK ? 7 : 0;
  if (!lv) continue;
  if (e.p.length && e.p.every((p) => PROPER.has(p))) { dropped++; continue; }
  if (e.p.length && e.p.every((p) => 'eyuo'.includes(p[0]))) { dropped++; continue; } // particles, interjections
  // Polyphones list one form per reading; the reading with the most senses is nearly always the everyday one.
  const f = e.f.reduce((best, x) => (x.m.length > best.m.length ? x : best), e.f[0]);
  const g = gloss(f.m);
  if (!g || (/[A-Z]/.test(f.i.y[0]) && lv === 7)) { dropped++; continue; }
  // Single characters with several readings make unfair test items; keep them for study, flag them out of the test.
  const fair = !(e.f.length > 1 && [...e.s].length === 1);
  levels[lv].push({ w: e.s, y: f.i.y.toLowerCase(), g, p: posClass(e.p) + (fair ? '' : '!'), q: e.q });
}

let out = '// GENERATED by tools/build-words.mjs. Do not edit.\n'
  + '// Word lists and frequency ranks: Complete HSK Vocabulary (MIT), https://github.com/drkameleon/complete-hsk-vocabulary\n'
  + '// Definitions: CC-CEDICT (CC BY-SA 4.0), https://www.mdbg.net/chinese/dictionary?page=cc-cedict\n'
  + '// One word per line, most frequent first: word, pinyin, gloss, part of speech (v n a d o; ! = kept out of the level check).\n'
  + 'export const WORDS = {\n';
for (const [lv, list] of Object.entries(levels)) {
  list.sort((a, b) => a.q - b.q);
  out += `  ${lv}: ${JSON.stringify(list.map((x) => [x.w, x.y, x.g, x.p].join('\t')).join('\n'))},\n`;
}
out += '};\n';
writeFileSync(join(dirname(fileURLToPath(import.meta.url)), '..', 'js', 'words.gen.js'), out);
console.log(Object.entries(levels).map(([l, a]) => `L${l}: ${a.length}`).join('  '), `| dropped ${dropped} | ${(out.length / 1024).toFixed(0)} KB`);
if (process.argv.includes('--sample')) for (const [lv, list] of Object.entries(levels)) console.log(lv, [0, 0.2, 0.4, 0.6, 0.8, 0.97].map((p) => { const x = list[Math.floor(list.length * p)]; return `${x.w} [${x.y}] ${x.g}`; }).join(' | '));
