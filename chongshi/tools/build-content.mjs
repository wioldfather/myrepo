// Generates js/content.gen.js from content/content.mjs:
//   - strips 字{pinyin} overrides and records pinyin for every Chinese string (PY map)
//   - cuts `ex` sentences into puzzle tiles
//   - builds HOMO, a toneless-pinyin → characters table used for speech matching and dictation decoys
// Run: npm run content            (add --review to print how every polyphonic character was read)
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { pinyin } from 'pinyin-pro';
import { LINES, SCENES, CHENGYU, REGISTER, TALKS, KIDS } from '../content/content.mjs';

const HAN = /[一-鿿]/;
const OVERRIDE = /([一-鿿])\{([^}]+)\}/g;
const PY = {};
const review = {};

function register(raw) {
  const forced = {};
  let n = 0;
  let clean = '';
  for (let i = 0; i < raw.length; i++) {
    const ch = raw[i];
    if (ch === '{') {
      const end = raw.indexOf('}', i);
      forced[n - 1] = raw.slice(i + 1, end);
      i = end;
      continue;
    }
    if (HAN.test(ch)) n++;
    clean += ch;
  }
  if (!n) return clean;
  const hanzi = [...clean].filter((c) => HAN.test(c));
  const py = pinyin(hanzi.join(''), { type: 'array' });
  if (py.length !== hanzi.length) throw new Error('pinyin length mismatch: ' + clean);
  // Corpus conventions the generator misses: erhua 儿, neutral-tone suffix 子, complement 得, and 一步一步.
  hanzi.forEach((c, i) => {
    const prev = hanzi[i - 1], next = hanzi[i + 1];
    if (c === '儿') py[i] = 'r';
    else if (c === '子' && next !== '轩') py[i] = 'zi';
    else if (c === '得' && py[i] === 'dé' && prev !== '两' && prev !== '患') py[i] = 'de';
    else if (c === '一' && py[i] === 'yi' && next === '步') py[i] = 'yí';
  });
  for (const [i, v] of Object.entries(forced)) py[i] = v;
  PY[clean] = py.join(' ');
  hanzi.forEach((c, i) => {
    const ctx = (hanzi[i - 1] || '·') + c + (hanzi[i + 1] || '·');
    ((review[c] ||= {})[py[i]] ||= new Set()).add(ctx);
  });
  return clean;
}

const strip = (s) => s.replace(OVERRIDE, '$1');

const scenes = SCENES.map((s) => ({
  ...s,
  zh: register(s.zh),
  lines: s.lines.map((l) => ({ ...l, zh: register(l.zh) })),
  qs: s.qs.map((q) => ({ ...q, q: register(q.q), opts: q.opts.map(register) })),
  chunks: s.chunks.map((c) => {
    const zh = register(c.zh);
    register(c.ex.replace(/\|/g, ''));
    return { ...c, id: zh, zh, ex: c.ex.split('|').map(strip), scene: s.id };
  }),
}));
const lines = LINES.map((l) => ({ ...l, zh: register(l.zh) }));
const chengyu = CHENGYU.map((y) => {
  const zh = register(y.zh);
  return { ...y, id: 'y:' + zh, zh, clue: register(y.clue) };
});
const talks = TALKS.map((t) => ({ ...t, zh: register(t.zh) }));
const k = (x) => ({ ...x, zh: register(x.zh) });
const kids = { sets: KIDS.sets.map((st) => ({ ...k(st), words: st.words.map(k) })), actions: KIDS.actions.map(k), home: KIDS.home.map((r) => ({ ...k(r), lines: r.lines.map(k) })) };
const reg = REGISTER.map((r, i) => ({ id: 'r' + (i + 1), sit: r.sit, opts: r.opts.map((o) => ({ ...o, zh: register(o.zh) })) }));

// sanity: unique ids, tiles rebuild their sentence
const ids = new Set();
for (const c of scenes.flatMap((s) => s.chunks)) {
  if (ids.has(c.id)) throw new Error('duplicate chunk: ' + c.id);
  ids.add(c.id);
  if (c.ex.length < 3) throw new Error('example needs at least 3 tiles: ' + c.ex.join(''));
}

// Homophone table: GB2312 level-1 characters (the 3,755 most common) plus anything else the corpus uses.
const dec = new TextDecoder('gb2312');
const common = new Set();
for (let hi = 0xb0; hi <= 0xd7; hi++) {
  for (let lo = 0xa1; lo <= 0xfe; lo++) {
    const ch = dec.decode(new Uint8Array([hi, lo]));
    if (HAN.test(ch)) common.add(ch);
  }
}
for (const text of Object.keys(PY)) for (const ch of text) if (HAN.test(ch)) common.add(ch);
const HOMO = {};
for (const ch of common) {
  const p = pinyin(ch, { toneType: 'none' });
  HOMO[p] = (HOMO[p] || '') + ch;
}

const out =
  '// GENERATED by tools/build-content.mjs. Do not edit; change content/content.mjs and run `npm run content`.\n' +
  `export const LINES = ${JSON.stringify(lines)};\n` +
  `export const SCENES = ${JSON.stringify(scenes)};\n` +
  `export const CHENGYU = ${JSON.stringify(chengyu)};\n` +
  `export const REGISTER = ${JSON.stringify(reg)};\n` +
  `export const TALKS = ${JSON.stringify(talks)};\n` +
  `export const KIDS = ${JSON.stringify(kids)};\n` +
  `export const PY = ${JSON.stringify(PY)};\n` +
  `export const HOMO = ${JSON.stringify(HOMO)};\n`;
const dest = join(dirname(fileURLToPath(import.meta.url)), '..', 'js', 'content.gen.js');
writeFileSync(dest, out);

const nChunks = scenes.reduce((n, s) => n + s.chunks.length, 0);
console.log(`${scenes.length} scenes, ${nChunks} chunks, ${chengyu.length} chengyu, ${reg.length} register items, ${Object.keys(PY).length} pinyin strings, ${(out.length / 1024).toFixed(0)} KB`);

if (process.argv.includes('--review')) {
  for (const [ch, readings] of Object.entries(review)) {
    if (Object.keys(readings).length < 2) continue;
    console.log(ch + '  ' + Object.entries(readings).map(([p, ctx]) => `${p}: ${[...ctx].join(' ')}`).join('  |  '));
  }
}
