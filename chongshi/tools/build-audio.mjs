// Recorded audio for scene lines and phrases.
//   node tools/build-audio.mjs plan              → audio/plan.json: batches of lines per voice, ready to send to a TTS service
//   node tools/build-audio.mjs cut <id> <file>   → aligns one batch's recording to its lines, stores audio/<id>.mp3,
//                                                   and records each line's place in js/audio.gen.js
// Each batch is one recording of several lines read in order; the app plays a line by seeking into it.
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { SCENES } from '../js/content.gen.js';
import { align } from './align-audio.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const planFile = join(root, 'audio', 'plan.json');
const genFile = join(root, 'js', 'audio.gen.js');
const MAX = 400; // characters per batch
const FEMALE = new Set(['小雨', '思琪']);
const size = (s) => [...s].length;

function plan() {
  const seen = new Set();
  const queues = { advisor: [], female: [], male: [], phrases: [] };
  for (const sc of SCENES) {
    for (const l of sc.lines) {
      if (seen.has(l.zh)) continue;
      seen.add(l.zh);
      queues[l.s === 'T' ? 'advisor' : FEMALE.has(sc.who) ? 'female' : 'male'].push({ text: l.zh, scene: sc.id });
    }
  }
  for (const sc of SCENES) for (const c of sc.chunks) if (!seen.has(c.zh)) { seen.add(c.zh); queues.phrases.push({ text: c.zh, scene: 'p' }); }
  const batches = [];
  for (const [voice, q] of Object.entries(queues)) {
    let cur = null;
    for (const item of q) {
      // keep a scene's lines together where possible; the first scene's student lines stand alone (already recorded as a pilot)
      const breakHere = !cur || cur.chars + size(item.text) > MAX || (voice === 'female' && cur.scenes.has('s1') && item.scene !== 's1');
      if (breakHere) { cur = { id: `${voice[0]}${String(batches.filter((b) => b.voice === voice).length + 1).padStart(2, '0')}`, voice, lines: [], chars: 0, scenes: new Set() }; batches.push(cur); }
      cur.lines.push(item.text);
      cur.chars += size(item.text) + 2;
      cur.scenes.add(item.scene);
    }
  }
  mkdirSync(join(root, 'audio'), { recursive: true });
  writeFileSync(planFile, JSON.stringify(batches.map(({ id, voice, lines }) => ({ id, voice, lines })), null, 1));
  for (const b of batches) console.log(b.id, b.voice, b.lines.length + ' lines', b.chars + ' chars');
  console.log(batches.length, 'batches,', batches.reduce((n, b) => n + b.chars, 0), 'characters');
}

function cut(id, file) {
  const batch = JSON.parse(readFileSync(planFile, 'utf8')).find((b) => b.id === id);
  if (!batch) throw new Error('no such batch: ' + id);
  const marks = align(file, batch.lines);
  const out = join(root, 'audio', id + '.mp3');
  // mono, constant bit rate: small, and seeking lands where the manifest says
  execFileSync('ffmpeg', ['-y', '-hide_banner', '-loglevel', 'error', '-i', file, '-ac', '1', '-ar', '44100', '-b:a', '48k', '-write_xing', '0', out]);
  const clips = existsSync(genFile) ? JSON.parse(readFileSync(genFile, 'utf8').match(/export const CLIPS = (\{[\s\S]*\});/)[1]) : {};
  batch.lines.forEach((t, i) => { clips[t] = [id, +marks[i].start.toFixed(2), +marks[i].end.toFixed(2)]; });
  writeFileSync(genFile, '// GENERATED by tools/build-audio.mjs. Where each recorded line sits: text → [file, start, end] in seconds.\nexport const CLIPS = ' + JSON.stringify(clips) + ';\n');
  const worst = marks.map((m, i) => [m.off, batch.lines[i]]).sort((a, b) => b[0] - a[0])[0];
  console.log(id, batch.lines.length, 'lines cut; least plausible:', (worst[0] * 100).toFixed(0) + '%', worst[1].slice(0, 16));
}

const [cmd, a, b] = process.argv.slice(2);
if (cmd === 'plan') plan(); else if (cmd === 'cut') cut(a, b); else console.log('usage: build-audio.mjs plan | cut <id> <file>');
